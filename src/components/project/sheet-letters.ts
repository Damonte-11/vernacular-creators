/** Column letters for a 0-based index: 0 → A, 26 → AA (the same as the sheet shows). */
export function columnLetterOf(index: number): string {
  let n = index + 1;
  let s = "";
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}
